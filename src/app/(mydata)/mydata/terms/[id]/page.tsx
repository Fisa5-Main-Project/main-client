export default function TermsDetailPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const scrollContainerRef = useRef<HTMLDivElement | null>(null);
  const [canConfirm, setCanConfirm] = useState(false);
  const router = useRouter();
  const toggleAgreement = useMyDataStore((state) => state.toggleAgreement);

  const resolvedParams = use(params);
  const termId = Number(resolvedParams.id);
  const termDetail = TERMS_DETAIL_CONTENTS[termId];

  if (!termDetail) {
    notFound();
  }

  useEffect(() => {
    const scrollEl = scrollContainerRef.current;
    if (!scrollEl) return;

    const updateCanConfirm = () => {
      const { scrollTop, scrollHeight, clientHeight } = scrollEl;
      const isBottomReached = scrollTop + clientHeight >= scrollHeight - 8;
      setCanConfirm(isBottomReached);
    };

    updateCanConfirm();
    scrollEl.addEventListener("scroll", updateCanConfirm);
    return () => {
      scrollEl.removeEventListener("scroll", updateCanConfirm);
    };
  }, [termDetail]);

  const handleConfirm = () => {
    if (!canConfirm) return;
    toggleAgreement(termId, true);
    router.push("/mydata/terms");
  };

  return (
    <div className="flex flex-col flex-grow h-full">
      <header className="flex items-center gap-4 mt-[3rem]">
        <Link
          href="/mydata/terms"
          
        >
          <ChevronRight className="w-8 h-8 text-secondary rotate-180" />
        </Link>
                <div>
                    <h1 className="text-[1.75rem] font-bold text-secondary">
                        {termDetail.title}
                    </h1>
                </div>
            </header>

      <div
        ref={scrollContainerRef}
        className="flex-grow mt-8 overflow-y-auto [-ms-overflow-style:'none'] [scrollbar-width:'none'] [&::-webkit-scrollbar]:hidden"
      >
        <div className="space-y-6">
          {termDetail.sections.map((section, index) => (
            <section
              key={section.title || index}
              className="rounded-2xl border border-gray-1 bg-gray-50 p-6"
                        >
                            <h2 className="text-lg font-semibold text-secondary">
                                {section.title}
                            </h2>
                            <p className="mt-3 whitespace-pre-line text-secondary leading-relaxed">
                                {section.body}
                            </p>
                        </section>
          ))}
        </div>
      </div>

      <div className="flex-shrink-0 mt-8">
        <Button onClick={handleConfirm} disabled={!canConfirm}>
          확인
        </Button>
      </div>
    </div>
  );
}
